/// Offset of the start-of-scan marker, and whether a Huffman table came before
/// it. Returns 0 when the data is not a JPEG this can walk.
inline size_t jpeg_find_scan(const uint8_t *data, size_t size, bool &has_dht) {
	has_dht = false;
	if (size < 4 || data[0] != 0xFF || data[1] != 0xD8) {
		return 0;
	}
	size_t i = 2;
	while (i + 4 <= size) {
		if (data[i] != 0xFF) {
			return 0;
		}
		const uint8_t marker = data[i + 1];
		if (marker == 0xFF) {   // fill byte
			i++;
			continue;
		}
		if (marker == 0xDA) {
			return i;
		}
		if (marker == 0xC4) {
			has_dht = true;
		}
		i += 2 + ((static_cast<size_t>(data[i + 2]) << 8) | data[i + 3]);
	}
	return 0;
}

/// A decodable copy of one MJPG frame: unchanged when it carries its own
/// Huffman tables, with the standard ones inserted before the scan otherwise.
inline void jpeg_with_tables(const uint8_t *data, size_t size, std::vector<uint8_t> &out) {
	bool has_dht = false;
	const size_t scan = jpeg_find_scan(data, size, has_dht);
	out.clear();
	if (scan == 0 || has_dht) {
		out.assign(data, data + size);
		return;
	}
	out.reserve(size + sizeof(JPEG_STANDARD_DHT));
	out.insert(out.end(), data, data + scan);
	out.insert(out.end(), JPEG_STANDARD_DHT, JPEG_STANDARD_DHT + sizeof(JPEG_STANDARD_DHT));
	out.insert(out.end(), data + scan, data + size);
}

