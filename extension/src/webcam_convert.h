inline uint8_t clamp8(int v) {
	return v < 0 ? 0 : (v > 255 ? 255 : static_cast<uint8_t>(v));
}

/// BT.601 limited range, which is what webcams send.
inline void yuv_to_rgb(int y, int u, int v, uint8_t *out) {
	const int c = 298 * (y - 16) + 128;
	const int d = u - 128;
	const int e = v - 128;
	out[0] = clamp8((c + 409 * e) / 256);
	out[1] = clamp8((c - 100 * d - 208 * e) / 256);
	out[2] = clamp8((c + 516 * d) / 256);
}

/// Packed YUY2 / YUYV (Y0 U Y1 V) to RGB8. `stride` is the bytes in a source row.
inline void yuy2_to_rgb(const uint8_t *src, ptrdiff_t stride, int width, int height, uint8_t *dst) {
	for (int row = 0; row < height; row++) {
		const uint8_t *s = src + row * stride;
		uint8_t *o = dst + static_cast<size_t>(row) * width * 3;
		for (int x = 0; x + 1 < width; x += 2) {
			yuv_to_rgb(s[0], s[1], s[3], o);
			yuv_to_rgb(s[2], s[1], s[3], o + 3);
			s += 4;
			o += 6;
		}
	}
}

/// NV12: a full-resolution Y plane, then one interleaved UV row for every two image rows.
inline void nv12_to_rgb(const uint8_t *src, ptrdiff_t stride, int width, int height, uint8_t *dst) {
	const uint8_t *uv_plane = src + stride * height;
	for (int row = 0; row < height; row++) {
		const uint8_t *y_row = src + row * stride;
		const uint8_t *uv_row = uv_plane + (row / 2) * stride;
		uint8_t *o = dst + static_cast<size_t>(row) * width * 3;
		for (int x = 0; x < width; x++) {
			const int pair = x & ~1;
			yuv_to_rgb(y_row[x], uv_row[pair], uv_row[pair + 1], o);
			o += 3;
		}
	}
}

/// 32-bit BGRX (Media Foundation's RGB32) to RGB8. `top_row` is the first byte of
/// the image's top row and `pitch` may be negative, for bottom-up bitmaps.
inline void bgrx_to_rgb(const uint8_t *top_row, ptrdiff_t pitch, int width, int height, uint8_t *dst) {
	for (int row = 0; row < height; row++) {
		const uint8_t *s = top_row + row * pitch;
		uint8_t *o = dst + static_cast<size_t>(row) * width * 3;
		for (int x = 0; x < width; x++) {
			o[0] = s[2];
			o[1] = s[1];
			o[2] = s[0];
			s += 4;
			o += 3;
		}
	}
}

/// 24-bit RGB or BGR rows with a stride, to tightly packed RGB8.
inline void rgb24_to_rgb(const uint8_t *src, ptrdiff_t stride, int width, int height, bool source_is_bgr, uint8_t *dst) {
	for (int row = 0; row < height; row++) {
		const uint8_t *s = src + row * stride;
		uint8_t *o = dst + static_cast<size_t>(row) * width * 3;
		for (int x = 0; x < width; x++) {
			o[0] = source_is_bgr ? s[2] : s[0];
			o[1] = s[1];
			o[2] = source_is_bgr ? s[0] : s[2];
			s += 3;
			o += 3;
		}
	}
}

